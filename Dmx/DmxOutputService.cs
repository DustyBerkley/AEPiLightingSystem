using System;
using System.IO.Ports;
using System.Runtime.InteropServices;
using System.Threading;

namespace AEPiLightingSystem.Dmx;

/// <summary>
/// Continuously transmits a <see cref="DmxUniverse"/> out a plain FTDI-based
/// USB-to-DMX cable (the cheap "Open DMX" style dongles - no framing
/// protocol of their own, just a raw serial-to-RS485 bridge). DMX512 has no
/// concept of "send an update" - a receiver only knows a channel's value
/// from the most recent full frame, so a dedicated thread re-sends the
/// entire universe in a tight loop for as long as the port is open.
///
/// Each frame is: a break (line held low) long enough for receivers to
/// recognize a new packet is starting, a short mark-after-break, then the
/// start code and 512 channel bytes at 250000 baud/8N2.
///
/// The break is generated by dropping to a much lower baud rate and writing
/// a single zero byte, rather than via <see cref="SerialPort.BreakState"/>
/// (Win32 SetCommBreak/ClearCommBreak). That API's timing is unreliable over
/// a USB-to-serial bridge - the break it produces can end up too short or
/// jittery, which a receiver reads as a corrupt/missing frame and falls back
/// to its own auto/chase behavior: exactly the symptoms seen with it
/// (spurious flashes with no audio, chaotic wrong-color strobing with
/// audio). A byte's own transmission time at a slow baud rate is precise -
/// governed by the UART, not OS scheduling - and easily tuned comfortably
/// past DMX's 92us minimum break.
/// </summary>
public sealed class DmxOutputService : IDisposable
{
    // 10 bits (1 start + 8 data + 1 stop) at this baud rate hold the line
    // low for ~417us - well past the 92us minimum break, with margin for
    // USB-to-serial jitter, but still short enough not to eat into frame
    // rate.
    private const int BreakBaudRate = 24000;
    private const int DmxBaudRate = 250000;
    private static readonly byte[] BreakByte = { 0x00 };

    // A single failed frame (one dropped USB transfer, one GC pause landing
    // at the wrong moment) used to kill the sender thread outright - DMX
    // output would go dark and stay dark until manually reconnecting. Retry
    // through isolated failures instead, and only give up - and tell the UI
    // - once they're persistent enough to mean the device is actually gone.
    private const int MaxConsecutiveFailures = 30;

    // Windows' default system timer resolution is ~15.6ms - fine for normal
    // apps, but DMX's break/MAB timing only has microseconds of slack, and
    // under CPU load (audio processing, general OS/UI activity) that coarse
    // resolution is exactly what lets Sleep(1) and the sender thread's
    // overall cadence drift enough to produce visibly more glitching than at
    // idle. Requesting 1ms resolution for as long as a DMX connection is
    // open tightens that back up. This is process-wide while requested, the
    // standard multimedia-app technique for this class of timing problem.
    [DllImport("winmm.dll", EntryPoint = "timeBeginPeriod")]
    private static extern uint TimeBeginPeriod(uint uPeriod);

    [DllImport("winmm.dll", EntryPoint = "timeEndPeriod")]
    private static extern uint TimeEndPeriod(uint uPeriod);

    private const uint TimerResolutionMs = 1;
    private bool _timerResolutionRaised;

    private readonly DmxUniverse _universe;
    private SerialPort? _port;
    private Thread? _senderThread;
    private volatile bool _running;

    public event EventHandler<Exception>? ConnectionLost;

    public bool IsConnected => _port is { IsOpen: true };

    public DmxOutputService(DmxUniverse universe)
    {
        _universe = universe;
    }

    public static string[] GetAvailablePorts() => SerialPort.GetPortNames();

    public void Connect(string portName)
    {
        Disconnect();

        var port = new SerialPort(portName, DmxBaudRate, Parity.None, 8, StopBits.Two)
        {
            Handshake = Handshake.None,
            WriteTimeout = 500,
        };
        port.Open();

        _port = port;
        _running = true;

        TimeBeginPeriod(TimerResolutionMs);
        _timerResolutionRaised = true;

        // DMX timing (break/MAB) is only microseconds of slack - under the
        // CPU load the lava lamp/audio pipeline adds once music is playing,
        // a lower-priority thread can get starved long enough to blow the
        // write timeout. Highest keeps it from being crowded out by that
        // other per-frame work (still below realtime/kernel priorities).
        _senderThread = new Thread(SenderLoop) { IsBackground = true, Name = "DMX Sender", Priority = ThreadPriority.Highest };
        _senderThread.Start();
    }

    public void Disconnect()
    {
        _running = false;
        _senderThread?.Join(200);
        _senderThread = null;

        _port?.Close();
        _port?.Dispose();
        _port = null;

        if (_timerResolutionRaised)
        {
            TimeEndPeriod(TimerResolutionMs);
            _timerResolutionRaised = false;
        }
    }

    private void SenderLoop()
    {
        var port = _port;
        if (port is null)
            return;

        var consecutiveFailures = 0;

        while (_running)
        {
            try
            {
                // Break: one zero byte at a slow baud rate holds the line
                // low for that byte's transmission time.
                port.BaudRate = BreakBaudRate;
                port.Write(BreakByte, 0, 1);
                Thread.Sleep(1);

                // Switching baud back (a USB control transfer round-trip)
                // plus this sleep comfortably covers the 12us minimum
                // mark-after-break before the real data starts.
                port.BaudRate = DmxBaudRate;
                Thread.Sleep(1);

                var frame = _universe.Frame;
                port.Write(frame, 0, _universe.FrameLength);

                consecutiveFailures = 0;
            }
            catch (Exception ex)
            {
                consecutiveFailures++;
                System.Diagnostics.Debug.WriteLine($"DMX frame send failed ({consecutiveFailures}/{MaxConsecutiveFailures}): {ex.Message}");

                if (consecutiveFailures >= MaxConsecutiveFailures)
                {
                    _running = false;
                    ConnectionLost?.Invoke(this, ex);
                    return;
                }
            }
        }
    }

    public void Dispose() => Disconnect();
}
